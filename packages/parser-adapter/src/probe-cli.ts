import { access, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isSource2Header, loadNativeParser, PARSER_LIBRARY_VERSION, sanitizeSchema, toRows } from './index.js';

const candidateEvents = ['round_start','round_freeze_end','round_end','round_officially_ended','player_death','player_hurt','bomb_planted','bomb_defused','bomb_exploded','player_blind','smokegrenade_detonate','flashbang_detonate','hegrenade_detonate','molotov_detonate'];
const demoArgument = process.argv.slice(2).find((argument) => argument !== '--');
if (!demoArgument) throw new Error('Использование: pnpm parser:probe -- path/to/demo.dem');
const demoPath = path.resolve(process.env.INIT_CWD ?? process.cwd(), demoArgument);
await access(demoPath);

const parser = loadNativeParser();
const header = parser.parseHeader(demoPath);
const players = toRows(parser.parsePlayerInfo(demoPath));
const listed = parser.listGameEvents(demoPath);
const eventNames = Array.isArray(listed) ? listed.filter((item): item is string => typeof item === 'string') : [];
const availableCandidates = candidateEvents.filter((name) => eventNames.includes(name));
const events = availableCandidates.length ? toRows(parser.parseEvents(demoPath, availableCandidates)) : [];
const eventTicks = [...new Set(events.map((row) => row.tick).filter((tick): tick is number => typeof tick === 'number' && Number.isInteger(tick)))].slice(0, 8);
// These properties are explicitly documented by demoparser2. We query only event-adjacent ticks.
const ticks = eventTicks.length ? toRows(parser.parseTicks(demoPath, ['team_num','team_name','team_rounds_total','is_alive'], eventTicks)) : [];

const report = {
  generatedAt: new Date().toISOString(), parserLibraryVersion: PARSER_LIBRARY_VERSION,
  source2Header: isSource2Header(header), headerKeys: header && typeof header === 'object' ? Object.keys(header).sort() : [],
  playerInfo: sanitizeSchema(players), listedEventCount: eventNames.length, availableCandidates,
  selectedEvents: sanitizeSchema(events), selectedTicks: sanitizeSchema(ticks)
};
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const outputPath = path.join(root, 'docs', 'compatibility.md');
await mkdir(path.dirname(outputPath), { recursive: true });
const markdown = `# Parser compatibility\n\n> Generated by \`pnpm parser:probe\`. Counts and column names only; player-identifying values are never written.\n\n- Probe status: **COMPLETE for supplied demo**\n- Generated: ${report.generatedAt}\n- Parser: \`@laihoe/demoparser2@${report.parserLibraryVersion}\`\n- Source 2 header: ${report.source2Header}\n- Header keys: ${report.headerKeys.map((x) => `\`${x}\``).join(', ')}\n- Player rows: ${report.playerInfo.count}; columns: ${report.playerInfo.columns.map((x) => `\`${x}\``).join(', ')}\n- Listed events: ${report.listedEventCount}\n- Candidate events present: ${report.availableCandidates.map((x) => `\`${x}\``).join(', ')}\n- Selected event rows: ${report.selectedEvents.count}; columns: ${report.selectedEvents.columns.map((x) => `\`${x}\``).join(', ')}\n- Selected tick rows: ${report.selectedTicks.count}; columns: ${report.selectedTicks.columns.map((x) => `\`${x}\``).join(', ')}\n`;
await writeFile(outputPath, markdown, 'utf8');
process.stdout.write(`${JSON.stringify(report, null, 2)}\nWrote ${outputPath}\n`);
